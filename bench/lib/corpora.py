"""Frozen corpora: fetch once, snapshot read-only, copy per version, write eulix's config."""
import os
import re
import shutil
import stat
import subprocess
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

from . import paths
from .common import REPO, SUITE, H, BenchError, run, say, write_json

MEASURES = {"indexing", "retrieval", "query", "parser"}
# `eulix init`'s default .euignore (eulix-cli/internal/cli/init.go).
EUIGNORE_DEFAULT = ["*.test*", "vendor/", "dist/", "test/", "build/"]


@dataclass(frozen=True)
class Corpus:
    name: str
    source: str
    commit: str
    measures: tuple
    tier: str = "default"
    tag: str = ""
    questions: str | None = None
    embed: bool = True
    index_repeats: int | None = None
    exclude: tuple = ()
    euignore_extra: tuple = field(default=())

    @property
    def id(self) -> str:
        return H({"name": self.name, "commit": self.commit, "exclude": sorted(self.exclude),
                  "euignore_extra": sorted(self.euignore_extra)})[:16]

    @property
    def label(self) -> str:
        return f"{self.name}@{self.tag or self.commit[:8]}"

    @property
    def snapshot(self) -> Path:
        return paths.sub("corpora", f"{self.name}-{self.commit[:12]}-{self.id[:8]}")

    def euignore(self) -> str:
        return "# Eulix ignore patterns (generated by bench)\n" + "".join(
            f"{p}\n" for p in [*EUIGNORE_DEFAULT, *self.euignore_extra])


def load_all(path: Path = SUITE / "corpora.toml") -> list[Corpus]:
    data = tomllib.loads(Path(path).read_text())
    if data.get("schema") != 1:
        raise BenchError(f"{path}: unsupported schema {data.get('schema')}")
    out, seen = [], set()
    for c in data.get("corpus", []):
        name = c["name"]
        if name in seen:
            raise BenchError(f"{path}: corpus {name} listed twice")
        seen.add(name)
        if not re.fullmatch(r"[0-9a-f]{40}", c.get("commit", "")):
            raise BenchError(f"{path}: corpus {name}: commit must be a full 40-hex SHA")
        bad = set(c.get("measures", [])) - MEASURES
        if bad:
            raise BenchError(f"{path}: corpus {name}: unknown measures {sorted(bad)}")
        if not c.get("embed", True) and "retrieval" in c.get("measures", []):
            raise BenchError(f"{path}: corpus {name}: retrieval needs embed = true")
        out.append(Corpus(name=name, source=c["source"], commit=c["commit"], measures=tuple(c["measures"]),
                          tier=c.get("tier", "default"), tag=c.get("tag", ""), questions=c.get("questions"),
                          embed=c.get("embed", True), index_repeats=c.get("index_repeats"),
                          exclude=tuple(c.get("exclude", ())), euignore_extra=tuple(c.get("euignore_extra", ()))))
    return out


def select(all_corpora: list[Corpus], names: list[str] | None, large: bool) -> list[Corpus]:
    if names:
        known = {c.name: c for c in all_corpora}
        missing = [n for n in names if n not in known]
        if missing:
            raise BenchError(f"unknown corpus: {', '.join(missing)} (known: {', '.join(known)})")
        return [known[n] for n in names]
    return [c for c in all_corpora if c.tier == "default" or (large and c.tier == "large")]


def _archive_into(git_dir: Path, commit: str, dest: Path) -> None:
    archive = subprocess.Popen(["git", "-C", str(git_dir), "archive", commit], stdout=subprocess.PIPE)
    tar = subprocess.run(["tar", "-x", "-C", str(dest)], stdin=archive.stdout)
    archive.stdout.close()
    if archive.wait() != 0 or tar.returncode != 0:
        raise BenchError(f"git archive {commit} from {git_dir} failed")


def _delete_excluded(root: Path, patterns) -> list[str]:
    removed = []
    for pat in patterns:
        if pat.endswith("/"):
            matches = [root / pat.rstrip("/")]
        elif pat.startswith("**/"):
            matches = list(root.rglob(pat[3:]))
        else:
            matches = list(root.glob(pat))
        for m in matches:
            if m.is_dir() and not m.is_symlink():
                shutil.rmtree(m)
            elif m.exists() or m.is_symlink():
                m.unlink()
            else:
                continue
            removed.append(str(m.relative_to(root)))
    return removed


def ensure_snapshot(c: Corpus) -> Path:
    """Fetch and freeze the corpus once. Files are made read-only so a stray write shows up."""
    snap = c.snapshot
    meta = snap.with_name(snap.name + ".json")
    if meta.exists() and snap.is_dir():
        return snap
    say(f"corpus {c.label}: fetching {c.source if c.source != 'self' else 'from this repo'}")
    tmp = snap.with_name(snap.name + ".tmp")
    _chmod_writable(tmp)
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    if c.source == "self":
        _archive_into(REPO, c.commit, tmp)
    else:
        mirror = paths.sub("corpora", "_git", f"{c.name}.git")
        if not mirror.exists():
            run(["git", "init", "--quiet", "--bare", mirror])
            run(["git", "-C", mirror, "remote", "add", "origin", c.source])
        if run(["git", "-C", mirror, "cat-file", "-e", f"{c.commit}^{{commit}}"], check=False).returncode != 0:
            run(["git", "-C", mirror, "fetch", "--quiet", "--depth", "1", "origin", c.commit])
        run(["git", "-C", mirror, "rev-parse", "--verify", f"{c.commit}^{{commit}}"])
        _archive_into(mirror, c.commit, tmp)
    removed = _delete_excluded(tmp, c.exclude)
    files = 0
    for p in tmp.rglob("*"):
        if p.is_file() and not p.is_symlink():
            p.chmod(p.stat().st_mode & ~(stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH))
            files += 1
    if snap.exists():
        _chmod_writable(snap)
        shutil.rmtree(snap)
    tmp.rename(snap)
    write_json(meta, {"name": c.name, "commit": c.commit, "tag": c.tag, "id": c.id, "files": files,
                      "excluded": removed})
    return snap


def _chmod_writable(root: Path) -> None:
    if not root.exists():
        return
    for p in [root, *root.rglob("*")]:
        if not p.is_symlink():
            try:
                p.chmod(p.stat().st_mode | stat.S_IWUSR)
            except OSError:
                pass


def remove_tree(root: Path) -> None:
    """rmtree that also handles the read-only files of a snapshot or a hardlinked work copy."""
    _chmod_writable(root)
    shutil.rmtree(root, ignore_errors=True)


def work_dir(c: Corpus, sha12: str, device: str) -> Path:
    return paths.sub("work", sha12 + ("-gpu" if device == "gpu" else ""), c.name)


def ensure_work(c: Corpus, sha12: str, device: str) -> Path:
    """A per-version copy of the snapshot (hardlinks: cheap, and the snapshot stays read-only)."""
    snap = ensure_snapshot(c)
    w = work_dir(c, sha12, device)
    if not (w / ".bench-src").exists():
        remove_tree(w)
        w.parent.mkdir(parents=True, exist_ok=True)
        run(["cp", "-al", snap, w])
        (w / ".bench-src").write_text(c.id + "\n")
    (w / ".euignore").write_text(c.euignore())
    return w


def render_config(engine: str | None) -> str:
    """eulix.toml for a run. etiya runs omit the engine line, which every version reads as etiya."""
    line = f'engine = "{engine}"' if engine and engine != "etiya" else "# engine: unset, the default (etiya)"
    text = (SUITE / "eulix.toml.tmpl").read_text().replace("{engine_line}", line)
    try:
        tomllib.loads(text)  # v0.8.3 silently ignores a broken file, so catch mistakes here
    except tomllib.TOMLDecodeError as e:
        raise BenchError(f"bench/suite/eulix.toml.tmpl renders invalid TOML: {e}")
    return text


def write_config(work: Path, engine: str | None) -> None:
    (work / "eulix.toml").write_text(render_config(engine))


def config_hash(c: Corpus) -> str:
    return H({"toml": render_config(None), "euignore": c.euignore()})[:16]


def reset_index(work: Path) -> Path:
    """A cold index: v0.8.3 skips analyze on an unchanged checksum, HEAD also keeps a parse cache."""
    d = work / ".eulix"
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir()
    return d


def preflight(c: Corpus, questions) -> None:
    """Questions must not appear verbatim in the corpus, and every expected path must exist."""
    snap = ensure_snapshot(c)
    rel_files = []
    texts = {q.text: q.id for q in questions}
    for p in snap.rglob("*"):
        if not p.is_file() or p.is_symlink():
            continue
        rel = p.relative_to(snap).as_posix()
        rel_files.append(rel)
        if p.stat().st_size > 4 << 20:
            continue
        try:
            body = p.read_text(errors="ignore")
        except OSError:
            continue
        for text, qid in texts.items():
            if text in body:
                raise BenchError(f"corpus {c.name}: {rel} quotes question {qid!r}; add it to `exclude` "
                                 f"in bench/suite/corpora.toml so retrieval can't find the question itself")
    for q in questions:
        if q.expect and not any(f.startswith(tuple(q.expect)) for f in rel_files):
            raise BenchError(f"corpus {c.name}: question {q.id!r} expects {q.expect}, which matches no file")


def du(path: Path, pattern: str = "*") -> int:
    return sum(p.stat().st_size for p in path.glob(pattern) if p.is_file())


def size_tree(path: Path) -> int:
    total = 0
    for root, _dirs, files in os.walk(path):
        for f in files:
            try:
                total += os.lstat(os.path.join(root, f)).st_size
            except OSError:
                pass
    return total
