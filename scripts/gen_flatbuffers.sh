# Regenerates the FlatBuffers code for every eulix-parser output from
# schema/*.fbs. The generated code is committed, so a normal build needs no
# flatc; run this (or `make schema`) after editing a schema, and bump
# KBFormatVersion (eulix-cli/internal/utils/constansts.go) and FORMAT_VERSION
# (libeulix/src/fb_io.rs) when the on-disk format changes.
#
# Usage: scripts/gen_flatbuffers.sh [--check]
#   --check  regenerate into a temp dir and fail if the committed code differs.

set -euo pipefail

FLATC_VERSION="25.12.19"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCHEMA_DIR="$ROOT/schema"
RUST_OUT="$ROOT/libeulix/src/fb"
GO_OUT="$ROOT/eulix-cli/internal/fb"
PY_OUT="$ROOT/eulix-embed/fb"

# Always use Google's release binary, downloaded once into a cache dir. A distro
# flatc can report the same version yet generate different code (Arch's
# 25.12.19-4 adds Python Create*Vector helpers), which breaks --check in CI.
# FLATC=/path/to/flatc overrides this, e.g. offline.
if [[ -z "${FLATC:-}" ]]; then
    case "$(uname -s)-$(uname -m)" in
        Linux-x86_64) asset="Linux.flatc.binary.g++-13.zip" ;;
        Darwin-arm64) asset="Mac.flatc.binary.zip" ;;
        Darwin-x86_64) asset="MacIntel.flatc.binary.zip" ;;
        *) echo "no flatc $FLATC_VERSION release binary for $(uname -sm); set FLATC" >&2; exit 1 ;;
    esac
    cache="${XDG_CACHE_HOME:-$HOME/.cache}/eulix/flatc-$FLATC_VERSION"
    FLATC="$cache/flatc"
    if [[ ! -x "$FLATC" ]]; then
        echo "downloading flatc $FLATC_VERSION ($asset)" >&2
        mkdir -p "$cache"
        curl -fsSL -o "$cache/flatc.zip" \
            "https://github.com/google/flatbuffers/releases/download/v$FLATC_VERSION/${asset//+/%2B}"
        unzip -oq "$cache/flatc.zip" -d "$cache"
        rm -f "$cache/flatc.zip"
        chmod +x "$FLATC"
    fi
fi
have="$("$FLATC" --version | awk '{print $3}')"
if [[ "$have" != "$FLATC_VERSION" ]]; then
    echo "$FLATC is version $have, but the generated code is pinned to $FLATC_VERSION" >&2
    exit 1
fi
flatc() { "$FLATC" "$@"; }

check=0
[[ "${1:-}" == "--check" ]] && check=1

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

shopt -s nullglob
schemas=("$SCHEMA_DIR"/*.fbs)

# Rust: one file per type. flatc nests output under the namespace path and
# rewrites mod.rs for every input schema, so the files are flattened into one
# module and mod.rs is written here instead. The generated files only use
# `use super::*;`, so they need no path fixups.
for s in "${schemas[@]}"; do
    flatc --rust --rust-module-root-file -o "$work/rust-raw" "$s"
done
mkdir -p "$work/rust"
cp "$work/rust-raw/eulix/fb/"*_generated.rs "$work/rust/"
{
    echo "// Automatically generated by scripts/gen_flatbuffers.sh. Do not modify."
    echo "// @generated"
    echo "#![allow(unsafe_code, unused_imports, clippy::all, clippy::pedantic)]"
    for f in $(cd "$work/rust" && command ls *_generated.rs | sort); do
        m="${f%.rs}"
        echo "mod $m;"
        echo "pub use self::$m::*;"
    done
} > "$work/rust/mod.rs"

# Go: flatc nests output under the namespace path; flatten into one package.
flatc --go -o "$work/go-raw" "${schemas[@]}"
mkdir -p "$work/go"
cp "$work/go-raw/eulix/fb/"*.go "$work/go/"
gofmt -w "$work/go"

# Python: flatc nests output under the namespace path and imports
# absolutely (eulix.fb.X); flatten into one package and make the imports
# relative, so eulix-embed/fb is a plain package like the Rust and Go ones.
flatc --python -o "$work/py-raw" "${schemas[@]}"
mkdir -p "$work/py"
cp "$work/py-raw/eulix/fb/"*.py "$work/py/"
perl -pi -e 's/^(\s*)from eulix\.fb\.(\w+) import/$1from .$2 import/' "$work/py/"*.py

sync_dir() { # src dst
    if (( check )); then
        if ! diff -r -x __pycache__ "$1" "$2" >/dev/null 2>&1; then
            echo "generated code in ${2#"$ROOT"/} is out of date; run scripts/gen_flatbuffers.sh" >&2
            diff -r -x __pycache__ "$1" "$2" | head -20 >&2 || true
            return 1
        fi
    else
        rm -rf "$2"
        mkdir -p "$(dirname "$2")"
        cp -r "$1" "$2"
    fi
}

status=0
sync_dir "$work/rust" "$RUST_OUT" || status=1
sync_dir "$work/go" "$GO_OUT" || status=1
sync_dir "$work/py" "$PY_OUT" || status=1
if (( ! check )); then
    echo "generated: ${RUST_OUT#"$ROOT"/}, ${GO_OUT#"$ROOT"/}, ${PY_OUT#"$ROOT"/}"
fi
exit $status
